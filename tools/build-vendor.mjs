// Builds the libraries in src/vendor/, each one minified script the page loads
// on demand (SHP.load):
//   source-tools.js  VS Code's CSS and HTML language services (completion,
//                    hover docs, CSS validation), HTMLHint and JSHint
//   js-tools.js      the TypeScript language service with the browser (DOM),
//                    ES2023 and jQuery type definitions, for JavaScript
//                    suggestions and hover docs
//   format-tools.js  Prettier with Shopify's Liquid plugin and Prettier's CSS
//                    and JavaScript parsers, for the Format button
// The extension has no build step, so the output is committed; rerun this
// (npm run vendor) after upgrading those packages.
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const modules = fileURLToPath(new URL('../node_modules/', import.meta.url));
const versions = (packages) => packages.map((p) => {
  const pkg = JSON.parse(readFileSync(`${modules}${p}/package.json`));
  return `${p}@${pkg.version} (${pkg.license})`;
});

const options = (name, packages) => ({
  entryPoints: [fileURLToPath(new URL(`./${name}.entry.js`, import.meta.url))],
  outfile: `src/vendor/${name}.js`,
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'chrome120',
  legalComments: 'none',
  banner: { js: `// Generated by tools/build-vendor.mjs; don't edit. Bundles ${versions(packages).join(', ')}.` },
});

await build(options('source-tools', ['vscode-css-languageservice', 'vscode-html-languageservice', 'vscode-languageserver-textdocument', 'htmlhint', 'jshint']));

await build({
  ...options('format-tools', ['prettier', '@shopify/prettier-plugin-liquid']),
  // The Liquid plugin's standalone build asks for require('prettier'), which
  // would pull in Prettier's Node build; the browser one has what it uses.
  // (Not esbuild's alias, which would also rewrite 'prettier/plugins/…'.)
  plugins: [{
    name: 'prettier-standalone',
    setup(b) {
      b.onResolve({ filter: /^prettier$/ }, (args) => b.resolve('prettier/standalone', { kind: args.kind, resolveDir: args.resolveDir }));
    },
  }],
});

// The .d.ts files the JavaScript language service reads, as { path: text }:
// TypeScript's own lib files (es2023, dom and everything they reference) under
// /lib/, and jQuery's (with Sizzle, which it uses) under /types/.
const declarations = () => {
  const files = {};
  const strip = (text) => text.replace(/^\/\*![\s\S]*?\*\/\s*/, ''); // license header
  const addLib = (name) => {
    const path = `/lib/lib.${name}.d.ts`;
    if (files[path]) return;
    files[path] = strip(readFileSync(`${modules}typescript/lib/lib.${name}.d.ts`, 'utf8'));
    for (const m of files[path].matchAll(/<reference lib="([^"]+)"/g)) addLib(m[1]);
  };
  ['es2023', 'dom', 'dom.iterable'].forEach(addLib);
  for (const file of ['JQueryStatic', 'JQuery', 'misc', 'legacy']) {
    files[`/types/jquery/${file}.d.ts`] = readFileSync(`${modules}@types/jquery/${file}.d.ts`, 'utf8');
  }
  // A module with "export as namespace Sizzle", which jQuery's files (scripts) can use.
  files['/types/sizzle/index.d.ts'] = readFileSync(`${modules}@types/sizzle/index.d.ts`, 'utf8');
  return files;
};

await build({
  ...options('js-tools', ['typescript', '@types/jquery', '@types/sizzle']),
  plugins: [{
    name: 'js-declarations',
    setup(b) {
      b.onResolve({ filter: /^slate-helper:js-declarations$/ }, (args) => ({ path: args.path, namespace: 'js-declarations' }));
      b.onLoad({ filter: /.*/, namespace: 'js-declarations' }, () => ({
        contents: `export default ${JSON.stringify(declarations())};`,
        loader: 'js',
      }));
    },
  }],
});
