// Builds src/vendor/source-tools.js: VS Code's CSS and HTML language services
// (completion, hover docs, CSS validation), HTMLHint and JSHint, as one
// minified script. The extension has no build step, so the output is
// committed; rerun this (npm run vendor) after upgrading those packages.
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';

const PACKAGES = ['vscode-css-languageservice', 'vscode-html-languageservice', 'vscode-languageserver-textdocument', 'htmlhint', 'jshint'];
const versions = PACKAGES.map((p) => {
  const pkg = JSON.parse(readFileSync(new URL(`../node_modules/${p}/package.json`, import.meta.url)));
  return `${p}@${pkg.version} (${pkg.license})`;
});

await build({
  entryPoints: [new URL('./source-tools.entry.js', import.meta.url).pathname.replace(/^\/(\w:)/, '$1')],
  outfile: 'src/vendor/source-tools.js',
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'chrome120',
  legalComments: 'none',
  banner: { js: `// Generated by tools/build-vendor.mjs; don't edit. Bundles ${versions.join(', ')}.` },
});
